returns table (test text, result text)
language plpgsql
security definer
set search_path = public
as $$
declare n int;
begin
  test := '0081 · ٥٢ مفتاح خروجات الأعضاء في القاعدة';
  select count(*) into n from copy_strings where key like 'host.%';
  if n >= 52 then result := format('نجح — %s مفتاح', n);
  else result := format('فشل — %s بس، الباقي هيقع على الاحتياطي', n); end if;
  return next;

  test := '0081 · كلهم تحت شاشة واحدة علشان يبانوا مع بعض في /admin/content';
  select count(distinct screen) into n from copy_strings where key like 'host.%';
  if n = 1 then result := 'نجح';
  else result := format('فشل — %s شاشة', n); end if;
  return next;

  test := '0081 · مفيش مفتاح قيمته فاضية';
  select count(*) into n from copy_strings where key like 'host.%' and btrim(value_ar) = '';
  if n = 0 then result := 'نجح';
  else result := format('فشل — %s مفتاح فاضي', n); end if;
  return next;
end;
$$;

