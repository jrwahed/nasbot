-- ============================================================================
-- 0111 — طقس الكشف: الرسالة بتفتح بنفس الجملة، والرابط بيودّي للمجموعة
--
-- تلات حاجات من نفس الجذر:
--
-- 1) **`booking_confirmed` كان لسه بيقول «الساعة 8 بالليل» بالحرف.**
--    `0109` وصّل ساعة الكشف بالإعدادات، وصلّح الموقع — والإيميل فضل كاتب
--    الرقم في جسمه. يعني المالك يغيّر الساعة من اللوحة، الموقع يقول الصح
--    والإيميل يقول 8. ده الدرس التلتاشر بالحرف: مصدر اتغيّر، وحد تاني
--    بيقرا منه ما مشيش وراه.
--    بقى `{{5}}` بييجي من `reveal_at` بتاع السبوطة نفسها — يعني مش ساعة
--    عامة، ده ميعاد الكشف بتاع الخروجة دي بالظبط.
--
-- 2) **رسالة الكشف مكانتش ليها طقس.** بتقول «مجموعتك بقت جاهزة» وبتودّي
--    على **الشات**. والشات مكان الكلام، مش مكان المجموعة — الصفحة اللي
--    فيها الأسامي والعلامة وإزاي تعرفهم هي `/my/<رقم الحجز>`.
--    دلوقتي الرسالة بتفتح بنفس الجملة كل مرة — «مجموعتك ظهرت» — والرابط
--    بيودّي لصفحة الحجز.
--
-- ⚠ الرابط نفسه بيتحسب في `src/lib/server/notify.ts` (كان `/me` لكل
--   الرسايل ما عدا التأكيد). أي تغيير في القوالب هنا لازم يمشي مع `CORE`
--   هناك، و`scripts/check-notify-vars.mjs` بيفشل البناء لو اختلفوا.
--
-- آمنة تتكرر: `update` بقيمة ثابتة.
-- ============================================================================

-- ⚠ النص **بين علامتي تنصيص واحدة وبأسطر حقيقية جواه** — مش `||chr(10)||`.
--    الحارس `scripts/check-notify-vars.mjs` بيقرا التعديلات دي بالشكل ده
--    بالظبط علشان يقارنها بـ`CORE`؛ لو كتبناها بالتلزيق، الحارس ما يشوفش
--    التعديل ويحكم على النص القديم ويقول «تمام» على غلط.
update notification_templates
   set body_ar = 'تمام يا {{1}}، مكانك محجوز.
{{2}} — {{3}}.
تفاصيل حجزك والمكان هنا: {{4}}
هتعرف مجموعتك {{5}}.
لو حصل أي تغيير من ناحيتنا، فلوسك بترجع كاملة.'
 where key = 'booking_confirmed';

update notification_templates
   set body_ar = 'يا {{1}}، مجموعتك ظهرت.
{{2}} — بكرة {{3}}.
شوف مين معاك وإزاي تعرفهم أول ما توصل: {{4}}
نشوفك هناك.'
 where key = 'group_reveal';


-- ===== دالة الاختبار =====
--
-- ⚠ شكلي بالضرورة — القوالب نصوص، والسلوك بتاعها (الإرسال) في الكود مش
--   في القاعدة. اللي بنتأكد منه هنا هو **اللي كان بيغلط**: مفيش ساعة
--   مكتوبة بالحرف، والمتغيّرات موجودة، والرسالة بتفتح بجملة الطقس.
create or replace function test_reveal_ritual()
returns table (test text, result text)
language plpgsql
set search_path = public
as $body$
declare
  v text;
  n int;
begin
  test := '0111 · مفيش ساعة كشف مكتوبة بالحرف في أي قالب';
  select count(*) into n from notification_templates
   where body_ar like '%الساعة 8 بالليل%' or body_ar like '%الساعة ٨%';
  if n = 0 then result := 'نجح';
  else result := format('فشل — %s قالب لسه كاتب الساعة في نصه', n); end if;
  return next;

  test := '0111 · تأكيد الحجز بيقول ميعاد الكشف بمتغيّر';
  select body_ar into v from notification_templates where key = 'booking_confirmed';
  if v like '%هتعرف مجموعتك {{5}}%' then result := 'نجح';
  else result := 'فشل — {{5}} مش موجودة في قالب التأكيد'; end if;
  return next;

  test := '0111 · رسالة الكشف بتفتح بجملة الطقس';
  select body_ar into v from notification_templates where key = 'group_reveal';
  if v like 'يا {{1}}، مجموعتك ظهرت.%' then result := 'نجح';
  else result := 'فشل — الافتتاحية اتغيّرت: ' || left(coalesce(v, '(مفيش قالب)'), 40); end if;
  return next;

  test := '0111 · رسالة الكشف بتودّي لصفحة الحجز مش للشات';
  if v like '%{{4}}%' and v not like '%افتح الشات%' then result := 'نجح';
  else result := 'فشل — لسه بتوصّل للشات بدل صفحة المجموعة'; end if;
  return next;

  -- ⚠ الدرس العاشر: بنتأكد إن اللي حطيناه موجود، مش إنه الوحيد.
  test := '0111 · القالبين نشطين';
  select count(*) into n from notification_templates
   where key in ('booking_confirmed', 'group_reveal') and is_active;
  if n = 2 then result := 'نجح';
  else result := format('فشل — %s من ٢ نشط', n); end if;
  return next;
end $body$;

comment on function test_reveal_ritual() is
  '0111 — قوالب التأكيد والكشف: مفيش ساعة مكتوبة بالحرف، والكشف بيفتح بجملة ثابتة وبيودّي لصفحة الحجز.';
