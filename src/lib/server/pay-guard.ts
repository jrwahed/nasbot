import 'server-only'

/**
 * ============================================================
 *  حارس وجهة التحويل — أخطر حاجة ممكن تحصل يوم الإطلاق
 * ============================================================
 *
 *  `settings.vodafone_number` و`settings.instapay_handle` بيتخلقوا بقيم
 *  افتراضية وهمية (`010 0000 0000` · `nasbot@instapay`) — هجرة 0033.
 *  ومسارات الدفع كانت بتمرّرهم للعضو **زي ما هم** من غير أي فحص.
 *
 *  يعني لو المالك نشر الموقع قبل ما يحط أرقامه الحقيقية، العضو هيشوف
 *  «حوّل على 010 0000 0000» ويبعت فلوسه لحد تاني خالص. والفلوس دي مش
 *  هتترجع، والعضو هيلوم نسبوط.
 *
 *  الحل: نرفض إنشاء الدفعة أصلًا ونقول السبب بوضوح. حجز متوقف بسبب مفهوم
 *  أحسن ألف مرة من فلوس ضايعة.
 */

/** الأرقام اللي بتيجي مع القاعدة وهي مش بتاعة حد */
const PLACEHOLDERS = ['010 0000 0000', 'nasbot@instapay']

/**
 * وجهة التحويل دي وهمية ولا حقيقية؟
 *
 * بنمسك: القيم الافتراضية بالحرف · الفاضي · وأي رقم كله أصفار بعد كود
 * الدولة (مثلاً 01000000000) — ده شكل الرقم اللي حد بيكتبه «مؤقتًا».
 */
export function isPlaceholderPayTo(v: string | null | undefined): boolean {
  const raw = (v ?? '').trim()
  if (!raw) return true
  if (PLACEHOLDERS.includes(raw)) return true
  const digits = raw.replace(/[\s-]/g, '')
  if (/^\+?2?0?1?0{6,}$/.test(digits)) return true
  return false
}

