/**
 * عارض تشديد بسيط: `**كده**` بتطلع غامقة.
 *
 * نصوص القضايا (البلاغ · الطريقة) فيها تشديد على الجملة المفتاحية —
 * «العقد لسه **في الصالون**» و«حاجة **ماينفعش يتكدب فيها**». من غير
 * العارض ده النجوم بتتعرض حرفيًا على الشاشة (وده اللي حصل فعلًا أول
 * ما الصفحة اتفتحت بالعين).
 *
 * ⚠ ده **مش** محلّل ماركداون — نجمتين وبس. أي حاجة تانية بتتعرض زي ما هي،
 *   علشان نص من اللوحة ما يقدرش يحقن شكل غريب في الصفحة.
 *
 * ⚠ وبياخد `null` عن قصد: نص القضية ساعات اختياري في القاعدة (كارت الدور ·
 *   المهمة · التلميح)، فالعارض بيرجّع فاضي بدل ما كل نداء يلف نفسه بشرط —
 *   من غير كده الحارس `check-case-em.mjs` بيضغط الناس إنها تتجاوزه.
 */
export function Em({ text }: { text: string | null | undefined }) {
  if (!text) return null
  const parts = text.split('**')
  return (
    <>
      {parts.map((p, i) =>
        i % 2 === 1 ? (
          <strong key={i} className="font-bold">
            {p}
          </strong>
        ) : (
          <span key={i}>{p}</span>
        ),
      )}
    </>
  )
}
