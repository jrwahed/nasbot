-- ===== دالة الاختبار =====
--
-- ⚠ بتفحص **البذرة** اللي المطابقة بتقف عليها: كتلة المطابقة الأخيرة موجودة،
--    مفيش اسم مرادف مكرر في كتلتين (وإلا الترتيب هو اللي بيقرر وده هش)،
--    وكل كتلة مرسومة ليها اسم. المطابقة نفسها بتتفحص في الكود
--    (`npm run verify` ← `scripts/check-map-match.ts`) لأنها عايشة هناك.
create or replace function test_map_blocks()
returns table (test text, result text)
language plpgsql security definer set search_path = public
as $body$
declare n int; dup text;
begin
  test := '0099 · كتلة المطابقة الأخيرة (other) موجودة ونشطة';
  if exists (select 1 from map_areas where key='other' and is_active)
    then result := 'نجح';
    else result := 'فشل — 🔴 أي منطقة مش معروفة هتختفي من الخريطة'; end if;
  return next;

  test := '0099 · كل كتلة مرسومة ليها اسم مرادف واحد على الأقل';
  select count(*) into n from map_areas
   where is_active and not is_mystery and w > 0 and coalesce(array_length(match_labels,1),0) = 0;
  if n = 0 then result := 'نجح';
  else result := format('فشل — %s كتلة من غير أسماء، مش هيوصلها حاجة', n); end if;
  return next;

  test := '0099 · مفيش اسم مرادف في كتلتين';
  select string_agg(distinct lbl, ' · ') into dup from (
    select unnest(match_labels) as lbl, key from map_areas where is_active
  ) q group by lbl having count(distinct key) > 1;
  if dup is null then result := 'نجح';
  else result := 'فشل — مكرر: ' || dup || ' — الترتيب هو اللي بيقرر وده هش'; end if;
  return next;

  test := '0099 · الكتل المرسومة ١٠ والبعيدة شرايط';
  select count(*) into n from map_areas where is_active and not is_mystery and w > 0;
  if n >= 8 then result := format('نجح — %s كتلة', n);
  else result := format('فشل — %s كتلة بس', n); end if;
  return next;

  test := '0099 · نصوص الخريطة مش بتوصف نقط اتشالت';
  if (select value_ar from copy_strings where key='map.text.4') like '%نقطة%'
    then result := 'فشل — العنوان لسه بيقول «دوس على أي نقطة» ومفيش نقط';
    else result := 'نجح'; end if;
  return next;
end $body$;

revoke execute on function test_map_blocks() from public, anon, authenticated;
