-- العلامة (اللي بتكتبها في «السبوطات») هي الرد على «هعرفهم إزاي؟». كانت
-- بتظهر في كرت «أول ربع ساعة» بعد الكشف بس — والعضو ساعتها بيكون قافل
-- الموقع. أكتر لحظة محتاجها فيها هي **وهو نازل**، يعني في تذكير الـ3
-- ساعات. الملف ده بيحطها فيه.
--
-- ⚠ **العلامة اختيارية.** لو السبوطة مفيهاش علامة، السطر بتاعها بيتشال من
--   الرسالة كلها — مش بيوصل «تعرفهم من: » ناقص. (نفس باج «وصلنا تحويلك
--   لـ .» القديم — دلوقتي فيه قاعدة عامة في الكود: **السطر اللي كل
