-- 0112 — العلامة بتوصل في تذكير الـ3 ساعات، والسبوطة من غير علامة بتتقال
--
-- العلامة (`sbotat.sign_ar`) هي الرد على «هعرفهم إزاي؟». اتعملت في `0107`
-- وبتظهر في كرت «أول ربع ساعة» بعد الكشف — بس العضو بيكون قافل الموقع
-- وهو في الطريق. أكتر لحظة محتاجها فيها هي **وهو نازل**، يعني في تذكير
-- الـ3 ساعات.
--
-- ⚠ **العلامة اختيارية**، ومش كل سبوطة ليها واحدة. فالسطر اللي فيها
--   بيتشال من الرسالة كلها لو فاضية — مش بيوصل «تعرفهم من: » ناقص.
--   القاعدة دي في `render` في `src/lib/server/notify.ts`: **السطر اللي كل
--   متغيّراته فضيت بيتشال**. (نفس الباج القديم بتاع «وصلنا تحويلك لـ .».)
--
-- ⚠ النص نص واحد بين علامتي تنصيص بأسطر حقيقية — علشان
--   `scripts/check-notify-vars.mjs` يقراه (شوف `0111`).
--
-- آمنة تتكرر: `update` بقيمة ثابتة + `create or replace`.
-- ============================================================================

update notification_templates
   set body_ar = 'فاضل 3 ساعات.
{{1}} هيكون مستنيك عند {{2}}.
تعرفهم من: {{3}}
اتطمن على وقتك، ونشوفك.'
 where key = 'reminder_3h';


-- ===== دالة الاختبار =====
--
-- ⚠ **الدرس العاشر**: الفاحص ده ما يقولش «كل السبوطات ليها علامة» — ده
--    هيبقى أحمر أول ما المالك يفتح مسوّدة جديدة، والأحمر الدايم بيتجاهل.
--    بيفشل في الحالة اللي فيها عطل **حقيقي** بس: سبوطة **اتكشفت خلاص**
--    (`reveal_at` عدّى) ولسه شغّالة ومفيهاش علامة — يعني فيه ناس بيفتحوا
--    كرت «أول ربع ساعة» دلوقتي ومش لاقيين إجابة.
create or replace function test_signs()
returns table (test text, result text)
language plpgsql
set search_path = public
as $body$
declare
  n   int;
  tot int;
begin
  test := '0112 · تذكير الـ3 ساعات فيه العلامة';
  select count(*) into n from notification_templates
   where key = 'reminder_3h' and body_ar like '%{{3}}%';
  if n = 1 then result := 'نجح';
  else result := 'فشل — {{3}} مش في قالب التذكير، فالعلامة مش بتوصل'; end if;
  return next;

  -- 🔴 العطل الحقيقي: اتكشفت وشغّالة ومفيهاش علامة
  --
  -- ⚠ سبوطة البذرة المؤقتة (`fn_test_seed_up`) مستثناة: هي بتبدأ بعد ٢٢
  --   ساعة يعني بتبقى «متكشفة» على طول، ومفيهاش علامة — فكانت هتخلّي
  --   الفاحص أحمر في كل تشغيل لـ`CHECK_DB`، والأحمر الدايم بيتجاهل.
  --   والاستثناء **بالـslug** (مفتاح ثابت) مش ببادئة رقم — الدرسين
  --   السابع والعاشر.
  test := '0112 · مفيش سبوطة اتكشفت وهي من غير علامة';
  select count(*) into n from sbotat s
    join sbota_templates t on t.id = s.template_id
   where s.status in ('open', 'full', 'locked', 'running')
     and s.reveal_at is not null and s.reveal_at <= now()
     and coalesce(btrim(s.sign_ar), '') = ''
     and t.slug <> 'test-fixture';
  if n = 0 then result := 'نجح';
  else result := format('فشل — %s سبوطة اتكشفت ومفيهاش علامة، والحاجزين مش عارفين يعرفوهم إزاي', n); end if;
  return next;

  -- صف معلومة — مش فشل. ده تنبيه للمالك قبل ما الميعاد ييجي.
  test := '0112 · سبوطات جاية لسه من غير علامة';
  select count(*) into n from sbotat s
    join sbota_templates t on t.id = s.template_id
   where s.status in ('draft', 'open', 'full')
     and s.starts_at > now()
     and coalesce(btrim(s.sign_ar), '') = ''
     and t.slug <> 'test-fixture';
  select count(*) into tot from sbotat s
    join sbota_templates t on t.id = s.template_id
   where s.status in ('draft','open','full') and s.starts_at > now()
     and t.slug <> 'test-fixture';
  if n = 0 then result := format('نجح — %s سبوطة جاية وكلها ليها علامة', tot);
  else result := format('معلومة — %s من %s سبوطة جاية لسه من غير علامة (اكتبها من «السبوطات»)', n, tot); end if;
  return next;
end $body$;

comment on function test_signs() is
  '0112 — العلامة في تذكير الـ3 ساعات، ومفيش سبوطة اتكشفت وهي من غير علامة.';
