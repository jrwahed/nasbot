-- ===== ١ · بيانات العرض تتمسح =====

-- السبوطات الأول (بتجرّ وراها الحجوزات والدفع والتقييمات والشات بالـcascade)
delete from sbotat;

-- الحجوزات المفروض راحت مع السبوطات — وده أمان لو فضل صف يتيم
delete from bookings;

-- الحجوزات المتكررة بتشاور على القوالب بـrestrict
delete from recurring_bookings
 where template_id in (select id from sbota_templates where not is_work);

-- الكباتن — الكابتن بقى اختياري خالص بعد نقلة ٢٠٢٦-٠٩-١٢
delete from captains;

-- القوالب: كل اللي مش شغل ومش القالب العام
delete from sbota_templates
 where not is_work and slug <> 'khroga-men-3odw';

-- الأماكن: اللي مش مربوط بمكان شغل بس
delete from venues v
 where not exists (select 1 from work_venues w where w.venue_id = v.id);

-- الأعضاء الوهميين: أي حد مالوش حساب دخول حقيقي ومش أدمن
delete from profiles p
 where not exists (select 1 from auth.users u where u.id = p.id and u.email is not null)
   and not exists (select 1 from admin_users a where a.profile_id = p.id);

