-- 0141 · مناطق «يلا» والكلمات الممنوعة — تحضير لميزة «يلا» (0142+)
--
-- طلب المالك (٢٠٢٦-١١-١٥): «المناطق من القايمة الموجودة. اتأكد إن العاشر
-- والشروق والعبور فيها، ولو مش موجودين ضيفهم».
--
-- القايمة الموجودة = `map_areas` (بتتعدّل من `/admin/map`، وهي اللي الخريطة
-- بتترسم منها). الحالة قبل الملف ده:
--   · **العبور** ✓ كتلة مرسومة.
--   · **الشروق** موجودة كـ`match_label` **جوه** العبور — يعني مش خيار لوحده.
--   · **العاشر من رمضان** مش موجودة في ولا كتلة ولا مرادف. وخروجة «بادل»
--     الحقيقية هناك بالظبط — فهي دلوقتي بتقع في كتلة «مناطق تانية».
--
-- ⚠ **ليه الاتنين `w = 0` (مش مرسومين)؟** `CairoMap` بيقسم الكتل لاتنين:
--   المرسومة جوه الـSVG (`not far and w > 0`)، والباقي بيبان **شرايط تحت
--   الخريطة**. فكتلة من غير هندسة **ما بتختفيش** — بتبان كبسولة. وده المطلوب:
--     · العاشر من رمضان `is_far = true` → بتبان دايمًا زي الفيوم والسخنة
--       (وهي فعلًا بره القاهرة — ساعة بالعربية).
--     · الشروق `is_far = false` → بتبان **بس لما يكون فيها خروجة**، علشان
--       ما نزحمش الشريط بمنطقة فاضية. وهي جوه القاهرة الكبرى مش بره.
--   لو رسمناهم كتل جديدة كان لازم نعيد توزيع الخريطة كلها، ولو سبناهم بره
--   الجدول كان أي خروجة فيهم **تختفي من الخريطة بالصمت** — وده بالظبط الباج
--   اللي `scripts/check-map-match.ts` اتكتب علشانه.
--
-- ⚠ **الترتيب (`sort`) هو اللي بيحدد المطابقة، مش النص.** `blockKeyFor`
--   بيلف على الكتل بترتيب `sort` وبياخد أول واحدة بتطابق. فالشروق لازم
--   تبقى **قبل** العبور (70) وإلا العبور بتكسبها (لسه عندها المرادف).
--   وسبنا المرادف في العبور عن قصد: ما بنلمسش صف `0099` خالص (الدرس التالت
--   — هجرتين بيكتبوا على نفس الصف = قنبلة موقوتة).
--
-- والكلمات الممنوعة: «نفر» و«الكابتن» اتضافوا لـ`banned_words` — **المصدر
-- الواحد** اللي `fn_guard_sbota_text` بيقرا منه، و`/admin/settings` ←
-- «الكلمات الممنوعة» بيعدّله. يعني ممنوعين في نصوص «يلا» وفي نصوص السبوطات
-- مع بعض. لو المالك احتاج واحدة منهم يشيلها من اللوحة في ثانية.
--
-- آمن يتكرر.
