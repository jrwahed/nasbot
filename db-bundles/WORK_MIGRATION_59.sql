-- ===== 1) الكتلتين =====
insert into map_areas
  (key, label_ar, area, match_labels, x, y, w, h, r, lx, ly, is_far, note_ar, is_mystery, sort, is_active)
values
  -- ⚠ `area` **null** في الاتنين عن قصد. `blockKeyFor` خطوته الأولى
  --   المطابقة بكود الـenum، و`other` محجوزة لكتلة الفيوم — فلو حطينا
  --   `other` هنا، كل خروجة في العاشر كانت هتروح الفيوم.
  ('shorouk', 'الشروق', null,
   array['الشروق','مدينة الشروق','شروق'],
   0, 0, 0, 0, 0, 0, 0, false, null, false, 65, true),

  ('3asher', 'العاشر من رمضان', null,
   array['العاشر من رمضان','العاشر','مدينة العاشر','العاشر من رمضان الشرقية'],
   0, 0, 0, 0, 0, 0, 0, true, 'ساعة', false, 115, true)
on conflict (key) do update set
  label_ar     = excluded.label_ar,
  area         = excluded.area,
  match_labels = excluded.match_labels,
  is_far       = excluded.is_far,
  note_ar      = excluded.note_ar,
  sort         = excluded.sort,
  is_active    = true,
  updated_at   = now();


-- ===== 2) الكلمات الممنوعة =====
insert into banned_words (word) values ('نفر'), ('الكابتن')
on conflict do nothing;


-- ===== 3) الاختبار =====
-- ⚠ **سلوكي**: إن الصف «موجود» ما يعنيش إن المطابقة بتوصله. بنشغّل نفس
--   منطق `blockKeyFor` بالـSQL (كود → اسم → ترتيب) وبنتأكد إن الاسم بيوصل
--   الكتلة الصح، وإن العبور ما اتكسرتش.
create or replace function test_yalla_areas()
returns table (test text, result text)
language plpgsql
set search_path = public
as $body$
declare
  -- كل استعلام تحت بيجيب **أول كتلة نشطة بترتيب `sort`** فيها الاسم في
  -- `label_ar` أو في المرادفات — نفس ترتيب `blockKeyFor` بالظبط.
  v_key text;
  n     int;
begin
  test := '0141 · الشروق بقت خيار لوحدها';
  select key into v_key from map_areas
   where is_active and ('الشروق' = label_ar or 'الشروق' = any (match_labels))
   order by sort limit 1;
  result := case when v_key = 'shorouk' then 'نجح'
                 else 'فشل — «الشروق» بتروح «' || coalesce(v_key, 'ولا حتة') || '»' end;
  return next;

  test := '0141 · العاشر من رمضان موجودة';
  select key into v_key from map_areas
   where is_active and ('العاشر من رمضان' = label_ar or 'العاشر من رمضان' = any (match_labels))
   order by sort limit 1;
  result := case when v_key = '3asher' then 'نجح'
                 else 'فشل — «العاشر من رمضان» بتروح «' || coalesce(v_key, 'ولا حتة') || '»' end;
  return next;

  -- ⚠ الشرط اللي بيمنع الانحدار: العبور نفسها لازم تفضل شغّالة.
  test := '0141 · العبور ما اتكسرتش';
  select key into v_key from map_areas
   where is_active and ('العبور' = label_ar or 'العبور' = any (match_labels))
   order by sort limit 1;
  result := case when v_key = 'obour' then 'نجح'
                 else 'فشل — 🔴 «العبور» بقت تروح «' || coalesce(v_key, 'ولا حتة') || '»' end;
  return next;

  -- ⚠ الشروق **قبل** العبور في الترتيب — ده الشرط اللي الخيار كله متعلّق بيه.
  test := '0141 · الشروق قبل العبور في الترتيب';
  select count(*) into n from map_areas a, map_areas b
   where a.key = 'shorouk' and b.key = 'obour' and a.sort < b.sort;
  result := case when n = 1 then 'نجح'
                 else 'فشل — 🔴 العبور بترتيب أقل، فهي اللي هتكسب «الشروق»' end;
  return next;

  -- ⚠ كتلة من غير هندسة لازم تبان شريط — `is_far` أو فيها خروجة. العاشر
  --   `is_far` فبتبان دايمًا؛ الشروق لأ وبتبان لما يكون فيها خروجة.
  test := '0141 · الكتلتين مش بيختفوا من الخريطة';
  select count(*) into n from map_areas
   where key in ('shorouk', '3asher') and w = 0 and is_active;
  result := case when n = 2 then 'نجح (شرايط تحت الخريطة)'
                 else format('فشل — %s من ٢ بس من غير هندسة', n) end;
  return next;

  test := '0141 · العاشر «بعيدة» ومعاها الوقت';
  select count(*) into n from map_areas
   where key = '3asher' and is_far and coalesce(btrim(note_ar), '') <> '';
  result := case when n = 1 then 'نجح'
                 else 'فشل — العاشر مش معلّمة «بعيدة» أو من غير وقت' end;
  return next;

  test := '0141 · «نفر» و«الكابتن» في الكلمات الممنوعة';
  select count(*) into n from banned_words where word in ('نفر', 'الكابتن');
  result := case when n = 2 then 'نجح'
                 else format('فشل — %s من ٢ بس', n) end;
  return next;
end $body$;

comment on function test_yalla_areas() is
  '0141 — الشروق والعاشر من رمضان بقوا خيارات مناطق، والعبور ما اتكسرتش، والكلمتين الممنوعة اتضافوا.';
revoke execute on function test_yalla_areas() from public, anon, authenticated;

