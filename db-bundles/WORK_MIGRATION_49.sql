create or replace function test_cases_content()
returns table (test text, result text)
language plpgsql
set search_path = public
as $body$
declare
  n int;
  m int;
begin
  -- (١) العوالم التلاتة لسه موجودة (بالـslug — الدرس العاشر)
  select count(*) into n from case_worlds where slug in ('mono','mission','whodunit');
  test := '0131 · العوالم التلاتة موجودة';
  result := case when n = 3 then 'نجح' else format('فشل — %s من 3', n) end;
  return next;

  -- (٢) القضايا التسعة
  select count(*) into n from cases where slug in
    ('aqd-elhanem','elgawab-elmaghool','waraqet-elyanaseeb',
     'elshafra','el3ameleen','elkhazna',
     'meen-kal-elmahshi','elremote','meen-sab-elgroup');
  test := '0131 · القضايا التسعة موجودة';
  result := case when n = 9 then 'نجح' else format('فشل — %s من 9', n) end;
  return next;

  -- (٣) 🔴 كل قضية ليها نهايتين ومقدمة وكارتين — القضية الناقصة بتوقّف اللعبة
  select count(*) into n from cases
   where btrim(coalesce(intro_ar,'')) = ''
      or btrim(coalesce(detective_card_ar,'')) = ''
      or btrim(coalesce(suspect_card_ar,'')) = ''
      or btrim(coalesce(win_ending_ar,'')) = ''
      or btrim(coalesce(escape_ending_ar,'')) = '';
  test := '0131 · 🔴 مفيش قضية ناقصة مقدمة أو كارت أو نهاية';
  result := case when n = 0 then 'نجح' else format('فشل — %s قضية ناقصة', n) end;
  return next;

  -- (٤) «العميلين» لمجموعة ٨+ · و«الخزنة» من غير متهم
  select count(*) into n from cases where slug = 'el3ameleen' and shape = 'double' and min_players >= 8;
  test := '0131 · «العميلين» شكلها double ولمجموعة ٨+';
  result := case when n = 1 then 'نجح' else 'فشل — شكل أو عدد غلط' end;
  return next;

  select count(*) into n from cases where slug = 'elkhazna' and shape = 'vault';
  test := '0131 · «الخزنة» شكلها vault';
  result := case when n = 1 then 'نجح' else 'فشل — شكل غلط' end;
  return next;

  -- (٥) «مين عملها؟» مفيهوش حدث في الفصل التاني
  select count(*) into n from case_worlds where slug = 'whodunit' and has_act2_event = false;
  test := '0131 · «مين عملها؟» مفيهوش حدث فصل تاني';
  result := case when n = 1 then 'نجح' else 'فشل' end;
  return next;

  -- (٦) «المهمة» بس هي اللي فيها أسماء حركية
  select count(*) into n from case_worlds where codenames and slug <> 'mission';
  test := '0131 · الأسماء الحركية في «المهمة» بس';
  result := case when n = 0 then 'نجح' else format('فشل — %s عالم زيادة', n) end;
  return next;

  -- (٧) 🔴 كل سؤال نشط ليه اختيارين على الأقل، وكل اختيار ليه تلميح.
  --     سؤال باختيار واحد = تلميح بينطبق على الكل = لعبة مكسورة.
  select count(*) into n from case_questions q
   where q.is_active
     and (select count(*) from case_options o where o.question_id = q.id) < 2;
  test := '0131 · 🔴 كل سؤال نشط ليه اختيارين على الأقل';
  result := case when n = 0 then 'نجح' else format('فشل — %s سؤال', n) end;
  return next;

  select count(*) into n from case_options where btrim(coalesce(clue_ar,'')) = '';
  test := '0131 · 🔴 كل اختيار ليه نص تلميح';
  result := case when n = 0 then 'نجح' else format('فشل — %s اختيار من غير تلميح', n) end;
  return next;

  -- (٨) التمنتاشر سؤال + سؤال اللبس
  select count(*) into n from case_questions where is_active and kind = 'answer';
  select count(*) into m from case_questions where is_active and kind = 'observed';
  test := '0131 · ١٨ سؤال إجابة + سؤال واحد على الأقل ما يتكدبش فيه';
  result := case when n >= 18 and m >= 1 then 'نجح'
                 else format('فشل — %s إجابة · %s ما يتكدبش', n, m) end;
  return next;

  -- (٩) عدد الأسئلة اللي الموقع بيسحبها لازم يكون أقل من أو يساوي الموجود
  select count(*) into n from case_questions where is_active and kind = 'answer';
  select case_questions_count into m from settings limit 1;
  test := '0131 · 🔴 بنك الأسئلة أكبر من أو يساوي اللي الموقع بيسحبه';
  result := case when n >= m then 'نجح'
                 else format('فشل — 🔴 الموقع بيسحب %s والبنك فيه %s', m, n) end;
  return next;

  -- (١٠) المهمات والألقاب
  select count(*) into n from case_missions where is_active;
  test := '0131 · بنك المهمات السرية فيه ١٢ على الأقل';
  result := case when n >= 12 then 'نجح' else format('فشل — %s مهمة', n) end;
  return next;

  select count(*) into n from case_titles where key in
    ('hawk_eye','actor','wronged','lawyer','honest','latecomer');
  test := '0131 · الألقاب الستة موجودة';
  result := case when n = 6 then 'نجح' else format('فشل — %s من 6', n) end;
  return next;

  -- (١١) 🔴 كل مهمة معلّقة على عالم، العالم ده موجود
  select count(*) into n from case_missions ms
   where ms.world_slug is not null
     and not exists (select 1 from case_worlds w where w.slug = ms.world_slug);
  test := '0131 · 🔴 مفيش مهمة معلّقة على عالم مش موجود';
  result := case when n = 0 then 'نجح' else format('فشل — %s مهمة', n) end;
  return next;

  -- (١٢) ربط التصنيفات بالعوالم — على القوالب اللي فعلًا موجودة
  select count(distinct t.kind::text) into n from sbota_templates t where t.case_world is not null;
  test := '0131 · القوالب اتربطت بعوالم';
  result := case when n >= 5 then 'نجح'
                 else format('معلومة — %s تصنيف متربط (المالك بيربط الباقي من اللوحة)', n) end;
  return next;
end $body$;

